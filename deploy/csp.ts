// Writes the nginx security-headers include for one build (P25).
//
// The pre-rendered pages contain inline scripts (theme, install prompt, React Router hydration).
// Their hashes change with every build, so the Content-Security-Policy is generated from the
// build output on every deploy, never typed by hand (docs/launch/headers.md).
//
// Output (in --out, default build/deploy/):
//   headers.conf.template  add_header lines; script-src holds __SCRIPT_HASHES__
//   script-hashes.txt      one 'sha256-…' per line
//   security-headers.conf  the template filled with this build's hashes (what nginx includes)
//
// On the server, deploy/remote/activate.sh fills the template itself: with the old and new
// release's hashes while it switches releases (no moment where a page's scripts are blocked),
// then with the new ones only.
//
//   node deploy/csp.ts [--build build/client] [--out build/deploy] [--report-only]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import {
  buildScriptHashes,
  contentSecurityPolicy,
  cspHeaderName,
  HASHES_PLACEHOLDER,
  SECURITY_HEADERS,
  SITE_ORIGIN,
} from './headers.ts';

/** One `add_header` line. Values are ours, but refuse anything nginx would read as syntax. */
export function addHeader(name: string, value: string): string {
  if (/["$\\\n]/.test(value) || !/^[A-Za-z-]+$/.test(name)) {
    throw new Error(`Header ${name} has a character nginx can't take in a quoted value`);
  }
  return `add_header ${name} "${value}" always;`;
}

export interface TemplateOptions {
  reportOnly?: boolean;
  extraConnect?: string[];
  /** Strict-Transport-Security value; empty → not sent (see DEPLOY_HSTS in .env.example). */
  hsts?: string;
}

/** The include with the hashes left as a placeholder. */
export function headersTemplate({
  reportOnly = false,
  extraConnect = [],
  hsts = '',
}: TemplateOptions = {}): string {
  const lines = [
    '# Snap Convert security headers. Generated by deploy/csp.ts for one build; do not edit.',
    '# Included in every location block of nginx-snap-convert.conf (add_header in a nested',
    '# location replaces the outer ones, so each block must include this file).',
    ...SECURITY_HEADERS.map(([name, value]) => addHeader(name, value)),
    ...(hsts.trim() ? [addHeader('Strict-Transport-Security', hsts.trim())] : []),
    addHeader(
      cspHeaderName(reportOnly),
      contentSecurityPolicy({ scriptHashes: HASHES_PLACEHOLDER, extraConnect }),
    ),
  ];
  return `${lines.join('\n')}\n`;
}

/** Same as activate.sh: the template with the hashes, space-separated. */
export function renderHeaders(template: string, hashes: string[]): string {
  const sorted = [...new Set(hashes)].sort();
  return template.split(HASHES_PLACEHOLDER).join(sorted.join(' '));
}

/** Parses `add_header Name "value" always;` lines (used by the local nginx stand-in). */
export function parseHeaders(conf: string): Array<[string, string]> {
  const out: Array<[string, string]> = [];
  for (const m of conf.matchAll(/^\s*add_header\s+([A-Za-z-]+)\s+"([^"]*)"\s+always;\s*$/gm)) {
    out.push([m[1] ?? '', m[2] ?? '']);
  }
  return out;
}

/** Reads KEY=VALUE lines (no expansion). Missing file → empty. */
export function readEnvFile(file: string): Record<string, string> {
  let text: string;
  try {
    text = readFileSync(file, 'utf8');
  } catch {
    return {};
  }
  const env: Record<string, string> = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq < 1) continue;
    let value = line.slice(eq + 1).trim();
    if (/^(['"]).*\1$/.test(value)) value = value.slice(1, -1);
    env[line.slice(0, eq).trim()] = value;
  }
  return env;
}

/**
 * The counter (P23) posts to VITE_UMAMI_URL. Same origin needs nothing; any other origin must be
 * allowed in connect-src or the CSP blocks it. Read from the same places Vite reads at build time.
 */
export function counterOrigins(root: string): string[] {
  const env = {
    ...readEnvFile(path.join(root, '.env')),
    ...readEnvFile(path.join(root, '.env.production')),
    ...process.env,
  };
  const url = env.VITE_UMAMI_URL?.trim();
  if (!url || !env.VITE_UMAMI_WEBSITE_ID?.trim()) return [];
  const origin = new URL(url).origin;
  return origin === SITE_ORIGIN ? [] : [origin];
}

export interface WrittenHeaders {
  hashes: string[];
  template: string;
  rendered: string;
  dir: string;
}

export function writeHeaders(
  buildDir: string,
  outDir: string,
  options: TemplateOptions = {},
): WrittenHeaders {
  const hashes = buildScriptHashes(buildDir);
  if (hashes.length === 0)
    throw new Error(`No inline scripts found in ${buildDir} — wrong folder?`);
  const template = headersTemplate(options);
  const rendered = renderHeaders(template, hashes);
  mkdirSync(outDir, { recursive: true });
  writeFileSync(path.join(outDir, 'headers.conf.template'), template);
  writeFileSync(path.join(outDir, 'script-hashes.txt'), `${hashes.join('\n')}\n`);
  writeFileSync(path.join(outDir, 'security-headers.conf'), rendered);
  return { hashes, template, rendered, dir: outDir };
}

/** Header options from deploy/.env (DEPLOY_CSP_REPORT_ONLY, DEPLOY_HSTS) and the app's .env. */
export function templateOptionsFromEnv(root: string): TemplateOptions {
  const env = { ...readEnvFile(path.join(root, 'deploy/.env')), ...process.env };
  return {
    reportOnly: env.DEPLOY_CSP_REPORT_ONLY === '1',
    hsts: env.DEPLOY_HSTS ?? '',
    extraConnect: counterOrigins(root),
  };
}

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const root = REPO_ROOT;
  const { values } = parseArgs({
    options: {
      build: { type: 'string', default: path.join(root, 'build/client') },
      out: { type: 'string', default: path.join(root, 'build/deploy') },
    },
  });
  const written = writeHeaders(
    path.resolve(values.build),
    path.resolve(values.out),
    templateOptionsFromEnv(root),
  );
  process.stdout.write(
    `Wrote ${path.join(written.dir, 'security-headers.conf')} (${written.hashes.length} inline-script hashes)\n`,
  );
}
